// Regenerates src/fonts/bundledFontData.ts from the woff2 files in assets/fonts.
//
// The files are embedded as base64 so the plugin serves them without reading
// its own install directory (which a bundler moves) and without a network
// request. Only the file endpoint imports the module, lazily, so the bytes are
// loaded the first time a visitor needs one and never during a build.
//
//   node scripts/build-bundled-fonts.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'assets', 'fonts')
const files = readdirSync(dir).filter((name) => name.endsWith('.woff2')).sort()

const entries = files
  .map((name) => `  '${name}': '${readFileSync(join(dir, name)).toString('base64')}',`)
  .join('\n')

writeFileSync(
  join(root, 'src', 'fonts', 'bundledFontData.ts'),
  `// Generated by scripts/build-bundled-fonts.mjs — do not edit.\nexport const BUNDLED_FONT_DATA: Record<string, string> = {\n${entries}\n}\n`,
)
console.log(`bundledFontData.ts: ${files.length} files`)
